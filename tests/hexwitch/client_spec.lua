local helpers = require("fixtures.helpers")
local client = require("hexwitch.ai.client")

describe("hexwitch.ai.client", function()
  before_each(function()
    vim.g.hexwitch_test_sync_mode = true
    vim.g.hexwitch_test_plenary_unavailable = nil
    helpers.setup_config()
  end)

  after_each(function()
    vim.g.hexwitch_test_sync_mode = nil
    vim.g.hexwitch_test_plenary_unavailable = nil
  end)

  describe("generate (request payload)", function()
    it("posts to base_url/chat/completions with the right headers and body", function()
      local captured, restore = helpers.mock_curl(function() return helpers.completion(helpers.valid_theme) end)
      client.generate("forest at full moon", function() end)

      assert.equals("https://api.openai.com/v1/chat/completions", captured[1].url)
      assert.equals("Bearer test-key", captured[1].headers.Authorization)
      assert.equals("application/json", captured[1].headers["Content-Type"])

      local body = captured[1].body
      assert.equals("gpt-4o-mini", body.model)
      assert.equals(0.7, body.temperature)
      assert.equals(2, #body.messages)
      assert.equals("system", body.messages[1].role)
      assert.equals("user", body.messages[2].role)
      assert.truthy(body.messages[2].content:match("forest at full moon"))
      restore()
    end)

    it("builds the URL from a custom base_url (OpenRouter / Ollama)", function()
      helpers.setup_config({ base_url = "http://localhost:11434/v1/" }) -- trailing slash
      local captured, restore = helpers.mock_curl(function() return helpers.completion(helpers.valid_theme) end)
      client.generate("x", function() end)
      assert.equals("http://localhost:11434/v1/chat/completions", captured[1].url)
      restore()
    end)

    it("sends the JSON schema when structured_output is true (default)", function()
      local captured, restore = helpers.mock_curl(function() return helpers.completion(helpers.valid_theme) end)
      client.generate("x", function() end)
      local rf = captured[1].body.response_format
      assert.equals("json_schema", rf.type)
      assert.equals("HexwitchThemeSchema", rf.json_schema.name)
      assert.is_true(rf.json_schema.strict)
      -- schema is the real 16-color one (compared by value: the body was JSON-encoded)
      assert.equals("^#[0-9A-Fa-f]{6}$", rf.json_schema.schema.properties.colors.properties.bg.pattern)
      assert.equals(16, #rf.json_schema.schema.properties.colors.required)
      restore()
    end)

    it("omits response_format when structured_output is false", function()
      helpers.setup_config({ structured_output = false })
      local captured, restore = helpers.mock_curl(function() return helpers.completion(helpers.valid_theme) end)
      client.generate("x", function() end)
      assert.is_nil(captured[1].body.response_format)
      restore()
    end)

    it("includes max_tokens only when configured", function()
      local captured, restore = helpers.mock_curl(function() return helpers.completion(helpers.valid_theme) end)
      client.generate("x", function() end)
      assert.is_nil(captured[1].body.max_tokens)
      restore()

      helpers.setup_config({ max_tokens = 512 })
      captured, restore = helpers.mock_curl(function() return helpers.completion(helpers.valid_theme) end)
      client.generate("x", function() end)
      assert.equals(512, captured[1].body.max_tokens)
      restore()
    end)
  end)

  describe("response parsing", function()
    it("parses theme JSON from message.content", function()
      helpers.mock_curl(function() return helpers.completion(helpers.valid_theme) end)
      client.generate("x", function(data, err)
        assert.is_nil(err)
        assert.equals("forest-moon", data.name)
        assert.equals("#0f1a14", data.colors.bg)
        assert.equals("gpt-4o-mini", data.model)
        assert.is_string(data.generated_at)
        assert.equals("api.openai.com", data.provider)
      end)
    end)

    it("prefers message.parsed when present (structured outputs)", function()
      helpers.mock_curl(function() return helpers.parsed_completion(helpers.valid_theme) end)
      client.generate("x", function(data, err)
        assert.is_nil(err)
        assert.equals("forest-moon", data.name)
      end)
    end)

    it("extracts JSON from a fenced ```json block (non-structured endpoints)", function()
      local fenced = { status = 200, body = vim.json.encode({
        choices = { { message = { content = "```json\n" .. vim.json.encode(helpers.valid_theme) .. "\n```" } } },
      }) }
      helpers.mock_curl(function() return fenced end)
      client.generate("x", function(data, err)
        assert.is_nil(err)
        assert.equals("forest-moon", data.name)
      end)
    end)
  end)

  describe("error paths", function()
    it("errors before any request when the API key is empty", function()
      helpers.setup_config({ api_key = "" })
      local saw = false
      client.generate("x", function(data, err)
        saw = true
        assert.is_nil(data)
        assert.truthy(err:match("API key not configured"))
      end)
      assert.is_true(saw)
    end)

    it("errors when plenary.curl is unavailable", function()
      vim.g.hexwitch_test_plenary_unavailable = true
      client.generate("x", function(data, err)
        assert.is_nil(data)
        assert.truthy(err:match("plenary.curl not available"))
      end)
    end)

    it("surfaces HTTP error status codes", function()
      helpers.mock_curl(function() return helpers.error_response(401, "bad key") end)
      client.generate("x", function(data, err)
        assert.is_nil(data)
        assert.truthy(err:match("API error: 401"))
        assert.truthy(err:match("bad key"))
      end)
    end)

    it("handles a non-JSON body", function()
      helpers.mock_curl(function() return { status = 200, body = "not json" } end)
      client.generate("x", function(data, err)
        assert.is_nil(data)
        assert.truthy(err:match("Failed to parse API response"))
      end)
    end)

    it("handles a null body (decodes to a non-table)", function()
      helpers.mock_curl(function() return { status = 200, body = "null" } end)
      client.generate("x", function(data, err)
        assert.is_nil(data)
        assert.truthy(err:match("Invalid response format"))
      end)
    end)

    it("handles empty choices", function()
      helpers.mock_curl(function() return { status = 200, body = vim.json.encode({ choices = {} }) } end)
      client.generate("x", function(data, err)
        assert.is_nil(data)
        assert.truthy(err:match("Invalid response format"))
      end)
    end)

    it("handles a message whose content is not parseable theme JSON", function()
      helpers.mock_curl(function()
        return { status = 200, body = vim.json.encode({ choices = { { message = { content = "no json here" } } } }) }
      end)
      client.generate("x", function(data, err)
        assert.is_nil(data)
        assert.truthy(err:match("Failed to parse theme data"))
      end)
    end)
  end)

  describe("refine", function()
    it("sends a refinement request and returns a full new theme", function()
      local captured, restore = helpers.mock_curl(function() return helpers.completion(helpers.refined_theme) end)
      client.refine(helpers.valid_theme, "make it warmer", function(data, err)
        assert.is_nil(err)
        assert.equals("forest-moon-warm", data.name)
      end)
      -- the refinement prompt must embed both the change and the current theme
      assert.truthy(captured[1].body.messages[2].content:match("make it warmer"))
      assert.truthy(captured[1].body.messages[2].content:match("forest%-moon"))
      restore()
    end)

    it("errors when there is no current theme to refine", function()
      client.refine(nil, "warmer", function(data, err)
        assert.is_nil(data)
        assert.truthy(err:match("No current theme"))
      end)
    end)
  end)

  describe("is_available", function()
    it("returns true when plenary.curl is loadable", function()
      assert.is_true(client.is_available())
    end)
    it("returns false under the plenary-unavailable test flag", function()
      vim.g.hexwitch_test_plenary_unavailable = true
      assert.is_false(client.is_available())
    end)
  end)
end)
